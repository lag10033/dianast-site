// ============================================================
//  ЗАКАЗЫ — история собранных заказов (общий модуль)
//
//  Подключается на страницах-калькуляторах (кладут позиции кнопкой «В заказ»)
//  и в разделе «Заказы» (показывает историю, правит, пересохраняет).
//
//  Хранение — localStorage, синхронизируется в облако как все dianast_*.
//    dianast_zakazy_v1       — список сохранённых заказов (история), новые в начале
//    dianast_zakaz_draft_v1  — текущий собираемый заказ (черновик), общий между страницами
//    dianast_zakaz_seq_v1    — счётчик номеров (З-1, З-2, …)
//
//  ПРАВИЛО РЕДАКТИРОВАНИЯ (задано владельцем 10.08.2026):
//    • контакты и комментарий правятся В ТОМ ЖЕ заказе (номер не меняется);
//    • изменение состава (позиции, количества) — это НОВЫЙ заказ, старый цел,
//      с пометкой «на основе №X». Историю задним числом не переписываем.
// ============================================================

const Заказы = (function () {
  const HKEY = 'dianast_zakazy_v1';
  const DKEY = 'dianast_zakaz_draft_v1';
  const SEQKEY = 'dianast_zakaz_seq_v1';

  const r2 = n => Math.round((parseFloat(n) || 0) * 100) / 100;
  const money = n => r2(n).toLocaleString('ru-RU', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  const ндсПроцент = () => (typeof ЦЕНЫ !== 'undefined' && ЦЕНЫ && ЦЕНЫ.ндс_процент != null) ? ЦЕНЫ.ндс_процент : 20;

  const читать = (k, деф) => { try { const v = JSON.parse(localStorage.getItem(k)); return v == null ? деф : v; } catch (e) { return деф; } };
  const писать = (k, v) => { try { localStorage.setItem(k, JSON.stringify(v)); } catch (e) {} };

  let история = читать(HKEY, []);
  let черновик = читать(DKEY, null);           // {позиции:[], клиент, коммент} — пока не сохранён

  const сохрИсторию = () => писать(HKEY, история);
  const сохрЧерновик = () => (черновик ? писать(DKEY, черновик) : localStorage.removeItem(DKEY));

  function следующийНомер() {
    let n = parseInt(читать(SEQKEY, 0), 10) || 0;
    n += 1; писать(SEQKEY, n); return n;
  }

  // Заказ и позиция — универсальны, не зависят от внутренностей калькуляторов.
  // позиция: { id, тип, наимен, ед, кол, цена, парам }   сумма = цена × кол (считается на лету)
  function нормПозиция(p, i) {
    return {
      id: p.id || ('p' + Date.now() + '_' + i),
      тип: p.тип || 'позиция',
      наимен: String(p.наимен || 'без названия'),
      ед: p.ед || 'шт',
      кол: r2(p.кол != null ? p.кол : (p.колво != null ? p.колво : 0)),
      цена: r2(p.цена || 0),
      парам: p.парам || null,          // исходные данные калькулятора — для будущей правки размеров
    };
  }
  const суммаПоз = p => r2((parseFloat(p.цена) || 0) * (parseFloat(p.кол) || 0));
  const итогБезНДС = поз => r2((поз || []).reduce((s, p) => s + суммаПоз(p), 0));
  function итоги(поз, ндс) {
    const без = итогБезНДС(поз);
    const н = r2(без * (ндс != null ? ндс : ндсПроцент()) / 100);
    return { безНДС: без, ндс: н, сНДС: r2(без + н), ндсПроц: ндс != null ? ндс : ндсПроцент() };
  }

  // ── ЧЕРНОВИК: калькуляторы кладут сюда позиции кнопкой «В заказ» ──
  function пустойЧерновик() { return { позиции: [], клиент: '', тел: '', почта: '', коммент: '' }; }

  function добавить(позиции, мета) {
    const список = (позиции || []).map(нормПозиция).filter(p => p.кол > 0);
    if (!список.length) return 0;
    if (!черновик) черновик = пустойЧерновик();
    список.forEach(p => черновик.позиции.push(p));
    сохрЧерновик();
    return черновик.позиции.length;
  }
  const вЧерновике = () => (черновик && черновик.позиции ? черновик.позиции.length : 0);
  const получитьЧерновик = () => черновик;
  function очиститьЧерновик() { черновик = null; сохрЧерновик(); }

  // Сохранить черновик как новый заказ в историю
  function сохранитьЧерновик() {
    if (!черновик || !черновик.позиции.length) return null;
    const н = следующийНомер();
    const t = Date.now();
    const заказ = {
      id: 'z' + t, num: н, наОснове: null,
      создан: t, изменён: t,
      клиент: черновик.клиент || '', тел: черновик.тел || '', почта: черновик.почта || '',
      коммент: черновик.коммент || '',
      позиции: черновик.позиции.map(нормПозиция),
      итог: итоги(черновик.позиции),
    };
    история.unshift(заказ);
    сохрИсторию();
    очиститьЧерновик();
    return заказ;
  }

  // ── ИСТОРИЯ ──
  const список = () => история.slice();
  const получить = id => история.find(z => z.id === id) || null;
  const номерПоId = id => { const z = получить(id); return z ? z.num : null; };

  // Правка контактов — в том же заказе (правило: контакты не плодят копию)
  function обновитьКонтакты(id, данные) {
    const z = получить(id); if (!z) return null;
    if (данные.клиент != null) z.клиент = данные.клиент;
    if (данные.тел != null) z.тел = данные.тел;
    if (данные.почта != null) z.почта = данные.почта;
    if (данные.коммент != null) z.коммент = данные.коммент;
    z.изменён = Date.now();
    сохрИсторию();
    return z;
  }

  // Правка состава — рождает НОВЫЙ заказ, старый цел
  function сохранитьКакНовый(базаId, позиции, контакты) {
    const родитель = получить(базаId);
    const н = следующийНомер();
    const t = Date.now();
    const c = контакты || {};
    const заказ = {
      id: 'z' + t, num: н,
      наОснове: родитель ? родитель.num : null,
      создан: t, изменён: t,
      клиент: c.клиент != null ? c.клиент : (родитель ? родитель.клиент : ''),
      тел: c.тел != null ? c.тел : (родитель ? родитель.тел : ''),
      почта: c.почта != null ? c.почта : (родитель ? родитель.почта : ''),
      коммент: c.коммент != null ? c.коммент : (родитель ? родитель.коммент : ''),
      позиции: (позиции || []).map(нормПозиция),
      итог: итоги(позиции || []),
    };
    история.unshift(заказ);
    сохрИсторию();
    return заказ;
  }

  function удалить(id) { история = история.filter(z => z.id !== id); сохрИсторию(); }
  function дублировать(id) {
    const z = получить(id); if (!z) return null;
    return сохранитьКакНовый(id, z.позиции, { клиент: z.клиент, тел: z.тел, почта: z.почта, коммент: z.коммент });
  }

  return {
    // черновик (для калькуляторов)
    добавить, вЧерновике, получитьЧерновик, очиститьЧерновик, сохранитьЧерновик,
    // история (для раздела «Заказы»)
    список, получить, номерПоId, обновитьКонтакты, сохранитьКакНовый, удалить, дублировать,
    // утилиты (раздел рисует итоги в одном стиле)
    суммаПоз, итоги, money,
  };
})();
if (typeof window !== 'undefined') window.Заказы = Заказы;
