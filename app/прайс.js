// ============================================================
//  ПРАЙС — единый ценовой движок DIANAST-app
//
//  Одна формула цены на все инструменты (отливы, доборные, раскрой, счёт),
//  чтобы одна и та же жесть везде считалась одинаково.
//
//  Модель — ГИБРИД (решение владельца 18.08.2026):
//    • по умолчанию цена = ПРАЙС по цвету: ЦЕНЫ.цвета[цвет][колонка] × наценка_прайса,
//      где колонка = 'обычное' (отлив, лист) | 'сложное' (доборные);
//    • если у выбранного клиента задан свой тариф (tariff > 0) — он ЗАМЕНЯЕТ прайс
//      (плоская ставка × наценка клиента), цвет тогда на цену не влияет.
//    • минималка: не ниже ЦЕНЫ.минималка (у клиента с тарифом — его minp);
//    • коэф_до_1500 (+15%): ТОЛЬКО сложным изделиям и только при длине ≤ 1,5 м.
//
//  Формула повторяет расчёт отливов (tools/otlivy/app.js) один-в-один —
//  подтверждено тестом parity (см. коммит). Отливы к модулю подключим на Этапе 2;
//  на Этапе 1 модуль используют доборные и раскрой вместо плоского тарифа 60.
//
//  Зависит от глобалей из цены.js: ЦЕНЫ (прайс), НАЦЕНКА_ПРОЦЕНТ.
//  Подключать ПОСЛЕ цены.js и ДО кода калькулятора.
// ============================================================

const Прайс = (function () {
  // тот же r2, что в отливах — иначе цифры разойдутся в копейках
  const r2 = x => Math.round(+((x || 0) * 100).toFixed(4)) / 100;

  const прайс = () => (typeof ЦЕНЫ !== 'undefined' && ЦЕНЫ) ? ЦЕНЫ : {};
  // общая наценка ко всему прайсу (из цены.js); у клиента со своим тарифом не применяется
  const idx = () => 1 + ((typeof НАЦЕНКА_ПРОЦЕНТ !== 'undefined' ? НАЦЕНКА_ПРОЦЕНТ : (прайс().наценка_процент || 0)) || 0) / 100;

  const цветПоId = цветId => (прайс().цвета || []).find(c => c.id === цветId) || null;
  // клиент участвует в цене только со своим тарифом (>0); иначе — обычный прайс
  const клиентСТарифом = клиент => (клиент && клиент.tariff > 0) ? клиент : null;

  // Ставка руб/м² (гибрид).
  //   { колонка:'обычное'|'сложное', цветId, своя (руб/м² для ручного цвета), клиент }
  function ставкаМ2(o) {
    o = o || {};
    const К = клиентСТарифом(o.клиент);
    if (К) return r2(К.tariff * (1 + (К.markup || 0) / 100));
    let базо;
    if (o.своя != null && o.своя !== '') базо = parseFloat(o.своя) || 0;
    else { const c = цветПоId(o.цветId); базо = c ? (parseFloat(c[o.колонка || 'обычное']) || 0) : 0; }
    return r2(базо * idx());
  }

  // Минимальная цена, руб (гибрид). У клиента с тарифом — его minp; иначе ЦЕНЫ.минималка × наценка.
  function минимум(o) {
    o = o || {};
    const К = клиентСТарифом(o.клиент);
    return К ? r2(К.minp || 0) : r2((прайс().минималка || 0) * idx());
  }

  // Коэффициент за короткие: только сложным и только при длине ≤ 1,5 м.
  function коэфКороткой(сложное, длинаМ) {
    const kk = прайс().коэф_до_1500 || 1.15;
    return (сложное && длинаМ > 0 && длинаМ <= 1.5) ? kk : 1;
  }

  // Ставка НДС, %: у клиента своя (vat), иначе из прайса.
  function ндс(клиент) {
    if (клиент && клиент.vat != null) return клиент.vat;
    const p = прайс();
    return p.ндс_процент != null ? p.ндс_процент : 20;
  }

  // Цена за ПОГ.М (отлив, доборный).
  //   { колонка, цветId, своя, клиент, ширинаМ (ширина/развёртка в МЕТРАХ), сложное, длинаМ, k }
  //   k — общий множитель заказа (срочность × повышающий), по умолчанию 1.
  function ценаПогМетра(o) {
    o = o || {};
    const m2 = ставкаМ2(o), minB = минимум(o);
    const kShort = коэфКороткой(o.сложное, o.длинаМ), k = o.k != null ? o.k : 1;
    return r2(Math.max(r2(m2 * (o.ширинаМ || 0)), minB) * kShort * k);
  }

  // Цена за ШТУКУ (плоский лист): площадь одного куска в м².
  //   { колонка, цветId, своя, клиент, площадьКускаМ2, сложное, длинаМ, k }
  function ценаШтуки(o) {
    o = o || {};
    const m2 = ставкаМ2(o), minB = минимум(o);
    const kShort = коэфКороткой(o.сложное, o.длинаМ), k = o.k != null ? o.k : 1;
    return r2(Math.max(r2(m2 * (o.площадьКускаМ2 || 0)), minB) * kShort * k);
  }

  return { r2, idx, цветПоId, ставкаМ2, минимум, коэфКороткой, ндс, ценаПогМетра, ценаШтуки };
})();
if (typeof window !== 'undefined') window.Прайс = Прайс;
