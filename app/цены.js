function _настройка(ключ, дефолт) {
  try {
    const v = JSON.parse(localStorage.getItem(ключ) || 'null');
    if (!v) return дефолт;
    const слито = Object.assign({}, дефолт, v);
    delete слито.демо;                       // настроено вручную — признак демо снимаем
    return слито;
  } catch (e) { return дефолт; }
}

